"""Explicit Python source scope keeps generated cache out of actual check proofs."""
from pathlib import Path
import os
import py_compile
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "skills/pipeline/scripts"))
import run_checks as C
import run_evidence as E
import run_policy as V
import run_state as R


class PythonSourceTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name).resolve()
        (self.root / "PIPELINE.md").write_text("fixture contract")
        self.src = self.root / "src"
        self.src.mkdir()
        (self.src / "module.py").write_text("VALUE = 1\n")
        (self.src / "config.json").write_text("{}")
        (self.root / "lock.txt").write_text("locked")
        state = R.start(self.root, managed=True)
        self.args = self.root, state["run_id"], state["owner_token"]
        V.acknowledge(*self.args, V.snapshot(self.root)["revision"])
        self.context = {"pipeline_input_profile": "python_source"}
        self.scope = ["src", "lock.txt"]
        self.argv = [sys.executable, "-c", "import os, sys; from pathlib import Path; "
                     "assert os.environ['PYTHONDONTWRITEBYTECODE']=='1'; "
                     "sys.path.insert(0, 'src'); import module; assert module.VALUE == 1; p=Path('counter'); "
                     "p.write_text(str(int(p.read_text())+1) if p.exists() else '1'); "
                     "raise SystemExit(Path('fail').exists())"]

    def check(self, name, **changes):
        return C.execute_check(*self.args, name, **(dict(argv=self.argv, scope=self.scope,
            environment=self.context, write_paths=["counter"], coverage=["unit"],
            impact_covered=True) | changes))

    def cache(self, name="module.cpython-313.pyc", data=b"cache"):
        directory = self.src / "__pycache__"
        directory.mkdir(exist_ok=True)
        path = directory / name
        path.write_bytes(data)
        return path

    def test_actual_execute_reuse_and_managed_qa_after_cache_changes(self):
        first = self.check("first")
        self.assertTrue(first["inputs_stable"])
        self.assertFalse((self.src / "__pycache__").exists())
        path = self.cache()
        self.cache("module.cpython-313.opt-1.pyc")
        path.write_bytes(b"changed generated bytecode")
        second = self.check("second")
        self.assertTrue(second["reused"])
        path.unlink()
        self.assertTrue(self.check("third")["reused"])
        self.assertEqual((self.root / "counter").read_text(), "1")
        qa = E.write_report(*self.args, "qa", "final", {"gate": "PASS",
            "checks": [first["report"]], "required_checks": ["unit"]})
        self.assertEqual(E.read_report(self.root, self.args[1], qa)["payload"]["gate"], "PASS")

    def test_source_config_lock_and_newer_failure_invalidate(self):
        first = self.check("first")
        for index, path in enumerate((self.src / "module.py", self.src / "config.json", self.root / "lock.txt")):
            path.write_text(path.read_text() + "\n")
            result = self.check(f"change{index}")
            self.assertFalse(result["reused"])
            self.assertEqual(result["reuse_decision"]["reason"], "inputs_changed")
        (self.root / "fail").touch()
        failure = self.check("failure", impact_covered=False)
        self.assertEqual(failure["exit_code"], 1)
        (self.root / "fail").unlink()
        self.assertFalse(self.check("after_failure", reuse_from=first["report"])["reused"])

    def test_cache_only_unknown_and_explicit_scopes_stay_strict(self):
        before = E.fingerprint(self.root, self.scope, self.context)
        path = self.cache()
        self.assertEqual(before, E.fingerprint(self.root, self.scope, self.context))
        strict = E.fingerprint(self.root, self.scope)
        explicit = E.fingerprint(self.root, ["src/__pycache__"], self.context)
        pyc = E.fingerprint(self.root, ["src/__pycache__/module.cpython-313.pyc"], self.context)
        path.write_bytes(b"new")
        self.assertNotEqual(strict, E.fingerprint(self.root, self.scope))
        self.assertNotEqual(explicit, E.fingerprint(self.root, ["src/__pycache__"], self.context))
        self.assertNotEqual(pyc, E.fingerprint(self.root, ["src/__pycache__/module.cpython-313.pyc"], self.context))
        for name in ("orphan.cpython-313.pyc", "module.pypy-313.pyc", "unknown.txt"):
            old = E.fingerprint(self.root, self.scope, self.context)
            self.cache(name)
            self.assertNotEqual(old, E.fingerprint(self.root, self.scope, self.context))
        old = E.fingerprint(self.root, self.scope, self.context)
        (self.src / "module.py").unlink()
        self.assertNotEqual(old, E.fingerprint(self.root, self.scope, self.context))

    def test_unsafe_symlinks_and_unknown_profile_rejected(self):
        path = self.cache()
        path.unlink()
        path.symlink_to(self.src / "module.py")
        with self.assertRaises(ValueError):
            E.fingerprint(self.root, self.scope, self.context)
        with self.assertRaises(ValueError):
            C.child_environment(None, {"pipeline_input_profile": "ignore_everything"})

    def test_old_strict_proof_cannot_upgrade(self):
        argv = [sys.executable, "-c", "print('strict proof')"]
        first = self.check("strict", argv=argv, environment={"scope": "local"})
        second = self.check("profile", argv=argv, reuse_from=first["report"])
        self.assertFalse(second["reused"])
        self.assertEqual(second["reuse_decision"]["reason"], "command_or_environment_changed")

    def test_valid_malicious_bytecode_cannot_change_actual_import(self):
        first = self.check("first")
        source = self.src / "module.py"
        original = source.stat()
        source.write_text("VALUE = 2\n")
        cache = self.cache(f"module.{sys.implementation.cache_tag}.pyc")
        py_compile.compile(str(source), cfile=str(cache), doraise=True)
        source.write_text("VALUE = 1\n")
        os.utime(source, ns=(original.st_atime_ns, original.st_mtime_ns))
        # Prove this is an executable cache attack, not an invalid pyc fixture.
        plain_env = dict(os.environ)
        plain_env.pop("PYTHONPYCACHEPREFIX", None)
        plain = subprocess.run([sys.executable, "-B", "-c",
            "import sys; sys.path.insert(0,'src'); import module; assert module.VALUE == 1"],
            cwd=self.root, env=plain_env, capture_output=True)
        self.assertNotEqual(plain.returncode, 0)
        self.assertTrue(self.check("reuse", reuse_from=first["report"])["reused"])
        self.assertEqual((self.root / "counter").read_text(), "1")
        actual = self.check("forced", impact_covered=False)
        self.assertEqual(actual["exit_code"], 0)
        self.assertTrue(actual["inputs_stable"])

    def test_env_ignoring_flags_and_existing_prefix_refused(self):
        for index, flags in enumerate((["-E"], ["-I"], ["-BE"], ["-X", "pycache_prefix="])):
            with self.assertRaisesRegex(ValueError, "honor its environment"):
                self.check(f"flags{index}", argv=[sys.executable, *flags, "-c", "print('unsafe')"])
        with patch.object(C.tempfile, "gettempdir", return_value=str(self.root)):
            prefix = Path(C._python_cache_prefix(self.root))
            prefix.mkdir()
            with self.assertRaisesRegex(ValueError, "must not exist"):
                self.check("exists")
            prefix.rmdir()
            prefix.symlink_to(self.root / "missing")
            with self.assertRaisesRegex(ValueError, "must not exist"):
                self.check("symlink")


if __name__ == "__main__":
    unittest.main()
